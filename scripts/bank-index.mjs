// Regenerates src/data/bank/index.ts from the files in src/data/bank: one lazy loader and a
// question count per topic. Run `npm run bank:index` after adding a topic file; check:questions
// fails if the index is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/data/bank");
const OUT = path.join(DIR, "index.ts");

export function buildIndex() {
  const topics = readdirSync(DIR)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .map((f) => f.slice(0, -3))
    .sort();
  const count = (id) => (readFileSync(path.join(DIR, `${id}.ts`), "utf8").match(/^\s*\{"id":/gm) ?? []).length;
  return `// Generated by \`npm run bank:index\` — do not edit by hand.
// Each topic's questions are a chunk of their own, fetched only when that topic is practised.
import type { BankQuestion } from "@/lib/bank";

export const BANK_LOADERS: Record<string, () => Promise<{ default: BankQuestion[] }>> = {
${topics.map((id) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(`./${id}`)}),`).join("\n")}
};

/** Questions per topic, so lists can show counts without loading any chunk. */
export const BANK_SIZES: Record<string, number> = {
${topics.map((id) => `  ${JSON.stringify(id)}: ${count(id)},`).join("\n")}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const src = buildIndex();
  writeFileSync(OUT, src);
  console.log(`bank index: ${(src.match(/import\(/g) ?? []).length} topics`);
}
